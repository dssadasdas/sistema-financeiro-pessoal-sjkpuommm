// Normaliza texto para busca (remove acentos e pontuação)
export function normalizeSearchString(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim()
}

// Encontra a instituição correspondente a partir de qualquer string (nome salvo, código, slug, apelido antigo)
