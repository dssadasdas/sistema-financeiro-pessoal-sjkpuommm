// Filtra instituições por termo de busca (nome, código, apelido, keywords)
export function searchInstitutions(query: string): FinancialInstitution[] {
  const clean = normalizeSearchString(query)
  if (!clean) return FINANCIAL_INSTITUTIONS

  return FINANCIAL_INSTITUTIONS.filter((inst) => {
    if (normalizeSearchString(inst.name).includes(clean)) return true
    if (normalizeSearchString(inst.shortName).includes(clean)) return true
    if (inst.code && inst.code.includes(clean)) return true
    if (inst.code && inst.code.padStart(3, '0').includes(clean)) return true
    if (inst.slug.includes(clean)) return true
    if (inst.keywords?.some((k) => normalizeSearchString(k).includes(clean))) return true
    return false
  })
}
